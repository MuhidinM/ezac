"use client";

import { RefreshCw, ClipboardCheck } from "lucide-react";

import { QueueCard } from "@/components/assessment/queue-card";
import { BranchAnalytics } from "@/components/branches/branch-analytics";
import { BranchCodesPanel } from "@/components/branches/branch-codes-panel";
import { CodeStatTiles } from "@/components/branches/code-stats";
import { InlineAlert } from "@/components/dashboard/inline-alert";
import { PageHeader } from "@/components/dashboard/page-header";
import { DetailList, Panel } from "@/components/dashboard/panel";
import { RequireRole } from "@/components/dashboard/require-role";
import { Button } from "@/components/ui/button";
import type { BranchPortalProfile } from "@/lib/api/types";
import { useResource } from "@/lib/api/use-resource";

export default function BranchPortalPage() {
  return (
    <RequireRole audience={["branch"]}>
      <BranchPortal />
    </RequireRole>
  );
}

function BranchPortal() {
  const { data: profile, error, isLoading, reload } = useResource<BranchPortalProfile>("/bff/branch/me");

  if (isLoading && !profile) {
    return <div className="h-72 animate-pulse rounded-xl bg-black/[0.04]" />;
  }

  if (!profile) {
    return (
      <section className="space-y-6">
        <PageHeader title="My branch" />
        <InlineAlert action={<Button variant="outline" size="sm" onClick={reload}>Retry</Button>}>
          {error?.message ?? "Branch profile not available"}
        </InlineAlert>
      </section>
    );
  }

  return (
    <section className="space-y-6">
      <PageHeader
        title={profile.name}
        description={
          [profile.woreda, profile.zone, profile.region].filter(Boolean).join(", ") ||
          "Your branch portal"
        }
        actions={
          <Button variant="outline" onClick={reload} disabled={isLoading}>
            <RefreshCw />
            Refresh
          </Button>
        }
      />

      <QueueCard
        status="SUBMITTED"
        title="Assessments to review"
        description="Submitted by field officers in your branch"
        icon={ClipboardCheck}
      />

      <BranchAnalytics />

      <CodeStatTiles stats={profile.codeStats} />

      <div className="grid gap-6 lg:grid-cols-2">
        <Panel title="Location">
          <DetailList
            items={[
              { label: "Region", value: profile.region },
              { label: "Zone", value: profile.zone },
              { label: "Woreda", value: profile.woreda },
            ]}
          />
        </Panel>
        <Panel title="Branch officer">
          <DetailList
            items={[
              { label: "Full name", value: profile.fullName },
              { label: "Phone (login)", value: profile.phone },
              { label: "Email", value: profile.email },
            ]}
          />
        </Panel>
      </div>

      <BranchCodesPanel listPath="/bff/branch/codes" />
      <p className="text-xs text-black/60">
        New codes are generated by head-office administrators.
      </p>
    </section>
  );
}
